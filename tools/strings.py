def esc(v):
    v = escape(v).replace("'", "\\'").replace('"', '\\"')
    if v.startswith("@") or v.startswith("?"):
        v = "\\" + v
    return v

def write(path, idx):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n')
        for k, v in S.items():
            extra = ' translatable="false"' if k == "app_name" and idx == 0 else ""
            if k == "app_name" and idx == 1:
                continue
            fmt = ' formatted="false"' if "%" in v[idx] and "%1$" not in v[idx] else ""
            f.write(f'    <string name="{k}"{extra}{fmt}>{esc(v[idx])}</string>\n')
        f.write('</resources>\n')

